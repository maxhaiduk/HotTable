-- Lab 1 data: customers and their orders, generated inside the database.
-- make seed ROWS=20000000  →  psql -v rows=20000000 -f seed.sql
\set ON_ERROR_STOP on
\timing on

SELECT greatest(:rows / 50, 1) AS customers \gset

-- Seeding only: let this session build indexes faster than the lab's server would.
SET maintenance_work_mem = '1GB';
SET max_parallel_maintenance_workers = 4;

DROP TABLE IF EXISTS orders, customers;

CREATE TABLE customers (
    id         bigint PRIMARY KEY,
    email      text        NOT NULL,
    created_at timestamptz NOT NULL
);

CREATE TABLE orders (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    customer_id bigint        NOT NULL,
    status      smallint      NOT NULL,
    amount      numeric(12,2) NOT NULL,
    created_at  timestamptz   NOT NULL,
    updated_at  timestamptz   NOT NULL,
    note        text
);

\echo 'customers...'
INSERT INTO customers (id, email, created_at)
SELECT g, 'customer' || g || '@example.com', now() - random() * interval '5 years'
FROM generate_series(1, :customers) AS g;

\echo 'orders: the longest step...'
-- One order every 5 seconds of history, so ids and created_at grow together as in real life.
INSERT INTO orders (id, customer_id, status, amount, created_at, updated_at, note)
SELECT g,
       1 + floor(random() * :customers)::bigint,
       floor(random() * 5)::smallint,
       round((random() * 1000)::numeric, 2),
       t.ts,
       t.ts,
       md5(g::text)
FROM generate_series(1, :rows) AS g,
     LATERAL (SELECT now() - make_interval(secs => (:rows - g) * 5) AS ts) AS t;

\echo 'primary key...'
ALTER TABLE orders ADD PRIMARY KEY (id);
SELECT setval(pg_get_serial_sequence('orders', 'id'), :rows);

\echo 'vacuum analyze...'
VACUUM (ANALYZE) customers, orders;

SELECT pg_size_pretty(pg_table_size('orders')) AS orders_table,
       pg_size_pretty(pg_indexes_size('orders')) AS orders_indexes;
